#!/usr/bin/env python3
"""Build the offline voice pack, pace-matched sounds and Metro asset manifest."""
from __future__ import annotations
import asyncio
import json
import subprocess
import tempfile
import wave
import shutil
from pathlib import Path
import edge_tts
from generate_sfx import generate_breath, generate_singing_bowl

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/assets/audio"
PROMPTS = json.loads((ROOT / "src/content/voice-prompts.json").read_text())

async def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    intermediates = Path(tempfile.mkdtemp(prefix="innerfire-voice-"))
    semaphore = asyncio.Semaphore(3)
    async def render(name: str, text: str) -> None:
        async with semaphore:
            for attempt in range(3):
                try:
                    await edge_tts.Communicate(
                        text, "en-AU-NatashaNeural", rate="-10%", pitch="-3Hz"
                    ).save(str(intermediates / f"{name}.mp3"))
                    subprocess.run([
                        "ffmpeg", "-y", "-loglevel", "error", "-i",
                        str(intermediates / f"{name}.mp3"),
                        "-af", "loudnorm=I=-18:TP=-2:LRA=7,afade=t=in:d=0.025",
                        "-ar", "44100", "-ac", "1", "-c:a", "pcm_s16le",
                        str(OUTPUT / f"{name}.wav"),
                    ], check=True)
                    print(f"Recorded {name}", flush=True)
                    return
                except Exception:
                    if attempt == 2:
                        raise
                    await asyncio.sleep(1 + attempt)
    await asyncio.gather(*(render(name, text) for name, text in PROMPTS.items()))
    for pace in range(10, 41, 5):
        cycle = pace / 10
        generate_breath(OUTPUT / f"inhale_{pace}.wav", cycle * 0.55 - 0.08, "inhale")
        generate_breath(OUTPUT / f"exhale_{pace}.wav", cycle * 0.45 - 0.08, "exhale")
    generate_breath(OUTPUT / "gentle_inhale.wav", 3.9, "inhale")
    generate_breath(OUTPUT / "gentle_exhale.wav", 5.9, "exhale")
    generate_singing_bowl(OUTPUT / "minute_marker.wav", 3)
    entries = []
    android_entries = []
    android_output = ROOT / "android/app/src/main/res/raw"
    android_output.mkdir(parents=True, exist_ok=True)
    for path in sorted(OUTPUT.glob("*.wav")):
        with wave.open(str(path)) as recording:
            duration = round(recording.getnframes() / recording.getframerate() * 1000)
        entries.append(
            f"  {path.stem}: {{asset: require('../assets/audio/{path.name}'), "
            f"durationMs: {duration}}},"
        )
        android_entries.append(f"  {path.stem}: {{asset: 0, durationMs: {duration}}},")
        shutil.copyfile(path, android_output / path.name)
    manifest = (
        "// Generated by scripts/build_audio.py. Bundled for offline use.\n"
        "export const AUDIO_CLIPS = {\n" + "\n".join(entries) +
        "\n} as const;\n\nexport type AudioClip = keyof typeof AUDIO_CLIPS;\n"
    )
    (ROOT / "src/constants/audio.ts").write_text(manifest)
    (ROOT / "src/constants/audio.android.ts").write_text(
        "// Generated Android raw-resource metadata.\nexport const AUDIO_CLIPS = {\n"
        + "\n".join(android_entries)
        + "\n} as const;\n\nexport type AudioClip = keyof typeof AUDIO_CLIPS;\n"
    )
    print(f"Bundled {len(entries)} files. Intermediates: {intermediates}")

if __name__ == "__main__":
    asyncio.run(main())
